"""Builds data.js (Mercer's database) from the team's synthetic dataset.

Run from the repo root:   python3 frontend/build_data.py
Re-run whenever synthetic_bank_transactions.csv or synthetic_financial_profile.xlsx changes.
Safe-to-spend uses the same calculate_forecast() as safe_to_spend.py, so numbers match the Streamlit app.
"""
import json, sys, types
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
# safe_to_spend.py imports streamlit only for UI decorators; stub it so this script has no UI dependency.
if "streamlit" not in sys.modules:
    try:
        import streamlit  # noqa: F401
    except ImportError:
        st = types.ModuleType("streamlit")
        st.cache_data = lambda *a, **k: (a[0] if a and callable(a[0]) else (lambda f: f))
        sys.modules["streamlit"] = st
from safe_to_spend import calculate_forecast  # noqa: E402

csv = ROOT / "synthetic_bank_transactions.csv"
xlsx = ROOT / "synthetic_financial_profile.xlsx"
df = pd.read_csv(csv)
df["posted_date"] = pd.to_datetime(df["posted_date"])
sheets = pd.read_excel(xlsx, sheet_name=None)

profile = {str(r.iloc[0]): r.iloc[1] for _, r in sheets["Profile & Rules"].iterrows()}
sav = sheets["Savings Transactions"]
bills = sheets["Recurring Bills"]
goals = sheets["Savings Goals"]

checking = float(df["running_balance_usd"].iloc[-1])
savings_bal = float(sav["Running savings balance ($)"].iloc[-1])
snapshot = df["posted_date"].max()
buffer = float(profile.get("Minimum checking buffer ($)", 500))
save_target = float(profile.get("Monthly savings goal ($)", 650))

fc = calculate_forecast(df, checking, snapshot, 30, save_target, buffer)
events = fc["events"]

txns = [
    {
        "date": r.posted_date.strftime("%Y-%m-%d"),
        "merchant": str(r.merchant),
        "category": str(r.category),
        "type": str(r.transaction_type),
        "amount": round(float(r.amount_usd), 2),
        "recurring": str(r.recurring).lower() == "yes",
        "balance": round(float(r.running_balance_usd), 2),
    }
    for r in df.itertuples()
]

data = {
    "source": "Synthetic demo data (team dataset). Fictional person; no real accounts.",
    "person": {"name": str(profile.get("Name", "Customer")), "employer": str(profile.get("Employer", "")),
               "payFrequency": str(profile.get("Pay frequency", "")), "payDays": "15th and last day of the month"},
    "asOf": snapshot.strftime("%Y-%m-%d"),
    "accounts": {"checking": round(checking, 2), "savings": round(savings_bal, 2),
                 "checkingMask": str(profile.get("Account checking masked", "****1842")),
                 "savingsMask": str(profile.get("Account savings masked", "****7721"))},
    "rules": {"buffer": buffer, "monthlySavings": save_target},
    "safeToSpend": {
        "amount": round(fc["safe"], 2), "days": 30, "bills": round(fc["bills"], 2),
        "variable": round(fc["variable"], 2), "savings": round(fc["savings"], 2), "buffer": round(fc["buffer"], 2),
        "variableMonthly": round(fc["variable_monthly"], 2),
        "upcoming": [{"date": e.Date.strftime("%Y-%m-%d"), "name": str(e.Bill), "category": str(e.Category),
                      "amount": round(float(e._4), 2)} for e in events.itertuples()],
    },
    "bills": [{"name": str(b["Bill"]), "payee": str(b["Payee"]), "category": str(b["Category"]),
               "amount": round(float(b["Expected amount ($)"]), 2), "day": int(b["Day of month"]),
               "priority": str(b["Priority"])} for _, b in bills.iterrows()],
    "goals": [{"name": str(g["Goal"]), "saved": round(float(g["Current funded ($)"]), 2),
               "target": round(float(g["Target ($)"]), 2), "monthly": round(float(g["Allocation / month ($)"]), 2),
               "deadline": pd.to_datetime(g["Deadline"]).strftime("%Y-%m-%d")} for _, g in goals.iterrows()],
    "transactions": txns,
}
out = Path(__file__).resolve().parent / "data.js"
out.write_text("/* Generated by build_data.py from the team's synthetic dataset. Do not edit by hand. */\n"
               "window.MERCER_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote {out.name}: {len(txns)} transactions, checking ${checking:,.2f}, savings ${savings_bal:,.2f}, "
      f"safe-to-spend ${fc['safe']:,.2f} (bills ${fc['bills']:,.2f}, variable ${fc['variable']:,.2f}), "
      f"{len(events)} upcoming bills")
